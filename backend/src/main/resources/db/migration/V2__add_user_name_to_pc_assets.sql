-- ============================================================
-- V2: pc_assets テーブルに user_name カラムを追加
--
-- エージェントが報告した使用者名（自由テキスト）を保存するカラム。
-- assigned_employee_id（社員FK）とは独立して管理し、
-- 社員マスタに一致しない場合でもエージェント入力値を表示できるようにする。
-- ============================================================
ALTER TABLE pc_assets
    ADD COLUMN user_name VARCHAR(200) NULL
        COMMENT 'エージェントが報告した使用者名（自由テキスト）'
        AFTER assigned_employee_id;
